def check_similarity(tensor1: torch.Tensor, tensor2: torch.Tensor) -> torch.Tensor:
    """
    Check weighted similarity between two 2D tensors using simple distance.
    Only compares positions where tensor1 > 0, using tensor1 values as weights.
    
    Args:
        tensor1: First input tensor of shape (N, M), used as weights when > 0
        tensor2: Second input tensor of shape (N, M)
        
    Returns:
        Weighted average similarity score (scalar)
    """
    # Verify input shapes match
    if tensor1.shape != tensor2.shape:
        raise ValueError(f"Tensor shapes must match. Got {tensor1.shape} and {tensor2.shape}")
    if len(tensor1.shape) != 2:
        raise ValueError(f"Tensors must be 2D. Got {len(tensor1.shape)} dimensions")

    # flatten the tensors
    tensor1 = tensor1.flatten()
    tensor2 = tensor2.flatten()

    # get the position of the top 5 values in tensor 2
    top_5_values, top_5_indices = torch.topk(tensor2, 4)

    # sum the top 5 values in tensor 1
    top_5_values_tensor1 = tensor1[top_5_indices]
    top_5_sum = top_5_values_tensor1.sum()
    
    return top_5_sum

